class SinglePatientDataset(Dataset):
    def __init__(self, patient_id: int, root_dir, split="train") -> None:
        self.img_transform = img_transform

        files = make_dataset(root_dir, split)

        print(files[:10])

        self.slice_paths = []
        for img_path, _ in files:
            if int(img_path.stem.split("_")[1]) == patient_id:
                self.slice_paths.append(img_path)

        if len(self.slice_paths) == 0:
            if split == "val":
                raise RuntimeError(f"Patient {patient_id} not found")
            self.__init__(patient_id, root_dir, split="val")

        print(len(self.slice_paths))

    def __len__(self):
        return len(self.slice_paths)

    def __getitem__(self, index: int):
        img = Image.open(self.slice_paths[index])

        return self.img_transform(img)


def save_prediction_nii(class_preds: np.ndarray, patient_id: int, out_path: Path):
    patient_name = f"Patient_{patient_id:02d}"
    ct_path = (
        autoroot.root
        / "data"
        / "segthor_part1"
        / "train"
        / patient_name
        / f"{patient_name}.nii.gz"
    )
    ct_nib = nib.load(str(ct_path))
    ct = np.asarray(ct_nib.dataobj)  # type: ignore

    assert class_preds.shape[0] == ct.shape[2], (class_preds.shape, ct.shape)
    # Upscale per-slice predictions back to the native in-plane resolution
    # (slices were resized down to 256x256 when generated by slice_segthor.py)
    target_shape = (ct.shape[0], ct.shape[1])
    class_preds = np.stack(
        [
            resize(pred, target_shape, order=0, preserve_range=True)
            for pred in class_preds
        ],
        axis=0,
    ).astype(np.uint8)

    vol = np.stack(class_preds, axis=2).astype(np.uint8)  # (x, y, z)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    nib.save(nib.Nifti1Image(vol, ct_nib.affine), str(out_path))
    print(f">> Saved prediction NIfTI to {out_path}")


def run_eval(args: "Args"):
    # Networks and scheduler
    device = (
        torch.device("cuda")
        if args.gpu and torch.cuda.is_available()
        else torch.device("cpu")
    )
    print(f">> Picked {device} to run experiments")

    num_classes: int = args.num_classes
    kernels: int = args.model.kernels
    factor: int = args.model.factor

    if args.model.name == "ENet":
        net = ENet(1, num_classes, kernels=kernels, factor=factor, dropoutRate=0)
    else:
        net = shallowCNN(1, num_classes, kernels=kernels, factor=factor, dropoutRate=0)

    net.load_state_dict(torch.load(args.weights, map_location=device))
    net.to(device)
    net.eval()

    data_dir = autoroot.root / "data/SEGTHOR"
    patient_dataset = SinglePatientDataset(args.patient_id, data_dir)
    data_loader = DataLoader(patient_dataset, args.batch_size)

    pred_tensor_list = []

    with torch.no_grad():
        for img in data_loader:
            pred_logits = net(img)
            # preds.shape = (batch_size, num_classes, W, H)
            pred_probs = F.softmax(
                args.model.temperature * pred_logits, dim=1
            )

            pred_seg = probs2class(pred_probs)

            pred_tensor_list.append(pred_seg.cpu().numpy())

    class_preds = np.concat(pred_tensor_list)
    print(np.min(class_preds), np.max(class_preds))

    if args.save_nii:
        out_path = args.nii_out
        if out_path is None:
            out_path = (
                autoroot.root
                / "results"
                / "predictions"
                / f"Patient_{args.patient_id:02d}_pred.nii.gz"
            )
        save_prediction_nii(class_preds, args.patient_id, out_path)


@dataclass
class Args:
    model: ModelConfig

    weights: Path

    num_classes: int = 5

    patient_id: int = 0

    data_dir: Path | None = None

    store_preds: bool = False
    gpu: bool = True

    batch_size: int = 8

    save_nii: bool = True
    nii_out: Path | None = None


def main():
    args = tyro.cli(Args)

    run_eval(args)


if __name__ == "__main__":
    main()

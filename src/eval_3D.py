def gaussian_window(size, sigma_scale=1 / 8):
    ws = []
    for s in size:
        x = torch.arange(s, dtype=torch.float32) - (s - 1) / 2
        ws.append(torch.exp(-0.5 * (x / (s * sigma_scale)) ** 2))
    w = ws[0][:, None, None] * ws[1][None, :, None] * ws[2][None, None, :]
    return (w / w.max()).clamp_min(1e-3)          # centre-weighted, never 0

def save_prediction_nii(class_preds: np.ndarray, patient_id: int, out_path: Path):
    patient_name = f"Patient_{patient_id:02d}"
    ct_path = (
        autoroot.root
        / "data"
        / "segthor_part1"
        / "train"
        / patient_name
        / f"{patient_name}.nii.gz"
    )
    ct_nib = nib.load(str(ct_path))
    ct = np.asarray(ct_nib.dataobj)  # type: ignore

    assert class_preds.shape[0] == ct.shape[2], (class_preds.shape, ct.shape)
    # Upscale per-slice predictions back to the native in-plane resolution
    # (slices were resized down to 256x256 when generated by slice_segthor.py)
    target_shape = (ct.shape[0], ct.shape[1])
    class_preds = np.stack(
        [
            resize(pred, target_shape, order=0, preserve_range=True)
            for pred in class_preds
        ],
        axis=0,
    ).astype(np.uint8)

    vol = np.stack(class_preds, axis=2).astype(np.uint8)  # (x, y, z)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    nib.save(nib.Nifti1Image(vol, ct_nib.affine), str(out_path))
    print(f">> Saved prediction NIfTI to {out_path}")

@torch.no_grad()
def predict_volume(net, img, box, overlap, K, batch_size, device, use_coords, temperature=1.0):
    """img: (C, D, H, W) float [0,1]. Returns (K, D, H, W) stitched probabilities."""
    C, D, H, W = img.shape
    d, h, w = box
    img_p = F.pad(img, (0, max(0, w - W), 0, max(0, h - H), 0, max(0, d - D)))  # same as training pad
    _, Dp, Hp, Wp = img_p.shape
    step = [max(1, int(s * (1 - overlap))) for s in box]
    starts = [(a, b, c) for a in window_starts(Dp, d, step[0])
                        for b in window_starts(Hp, h, step[1])
                        for c in window_starts(Wp, w, step[2])]
    win = gaussian_window(box).to(device)
    prob_sum = torch.zeros((K, Dp, Hp, Wp), device=device)
    w_sum = torch.zeros((Dp, Hp, Wp), device=device)

    for i in range(0, len(starts), batch_size):
        chunk = starts[i:i + batch_size]
        xs = []
        for a, b, c in chunk:
            x = img_p[:, a:a + d, b:b + h, c:c + w]
            if use_coords:
                x = torch.cat([x, torch.from_numpy(coord_grid((D, H, W), (a, b, c), box))])
            xs.append(x)
        probs = F.softmax(temperature * net(torch.stack(xs).to(device)).float(), dim=1)
        for p, (a, b, c) in zip(probs, chunk):
            prob_sum[:, a:a + d, b:b + h, c:c + w] += p * win
            w_sum[a:a + d, b:b + h, c:c + w] += win
    return (prob_sum / w_sum)[:, :D, :H, :W]

def run_eval(args: "Args"):
    device = torch.device("cuda" if args.gpu and torch.cuda.is_available() else "cpu")
    cfg = Config(model=args.model, dataset=args.dataset)
    K = cfg.dataset.num_classes
    net = get_model(cfg)
    net.load_state_dict(torch.load(args.weights, map_location=device))
    net.to(device).eval()

    root = autoroot.root / "data" / cfg.dataset.name
    ds = BoxDataset(args.split, root, sub_box_size=None, num_classes=K)   # whole volumes, no transforms
    spacing_map = load_spacing(root)

    results = {}
    for item in ds.items:
        if args.patient_id is not None and item["stem"] != f"Patient_{args.patient_id:02d}":
            continue
        img = torch.from_numpy(item["img_vol"]).float() / 255.0
        probs = predict_volume(net, img, cfg.dataset.box_size, args.overlap, K, args.batch_size,
                            device, cfg.dataset.use_coords, cfg.model.temperature)
        pred = probs.max(dim=0).indices.cpu().numpy().astype(np.uint8)     # (D, 256, 256)

        gt_xyz, spacing, affine = load_native_gt(autoroot.root / "data", item["stem"])
        pred_xyz = to_native_space(pred, gt_xyz.shape)                     # back to 512x512, native grid
        results[item["stem"]] = evaluate_patient(pred_xyz, gt_xyz, spacing)
        print(item["stem"], results[item["stem"]])

        if args.submission_dir:
            write_submission(pred_xyz, affine, item["stem"], args.submission_dir)

    write_csv(results, args.csv_out)
    print(f">> Wrote metrics to {args.csv_out}")

@dataclass
class Args:
    model: ModelConfig
    dataset: DatasetConfig
    weights: Path
    split: str = "val"
    patient_id: int | None = None      # None = all patients in the split
    overlap: float = 0.5
    gpu: bool = True
    batch_size: int = 4
    save_nii: bool = True
    nii_out: Path | None = None
    csv_out: Path = Path("results/metrics.csv")
    submission_dir: Path | None = None